test("legacy thumbnails coalesce, revalidate bytes and deny revoked access even with matching validators",async()=>{
  const path="/api/media/legacy/903/thumbnail";
  const previews=await Promise.all(Array.from({length:6},()=>call(path)));
  assert.ok(previews.every(r=>r.status===200));assert.equal(conversions,1);
  const first=previews[0],etag=first.headers.get("etag");assert.ok(etag);
  const firstBytes=Buffer.from(await first.arrayBuffer());
  assert.match(first.headers.get("cache-control"),/private, no-cache.*must-revalidate/);
  assert.equal(first.headers.get("vary"),"Cookie");
  assert.equal((await call(path,etag)).status,304);assert.equal(conversions,1);
  const old=media.thumbnail;
  media.thumbnail=old.replace(/,(.{40})/,",$1\n");
  const reformatted=await call(path,etag);assert.equal(reformatted.status,200);
  assert.notEqual(reformatted.headers.get("etag"),etag);
  assert.deepEqual(Buffer.from(await reformatted.arrayBuffer()),firstBytes,"Source validator changes even if generated bytes are identical");
  media.thumbnail=`data:image/webp;base64,${bytes.toString("base64")}`;
  const changed=await call(path,etag);assert.equal(changed.status,200);assert.notEqual(changed.headers.get("etag"),etag);
  media.thumbnail=old;
  await checkRevocations(path,etag);
});
async function checkRevocations(path,etag){
  for(const [target,change] of [
    [event,{adminHidden:true}],[event,{isPremium:true}],[event,{visibility:"draft"}],
    [event,{safetyStatus:"review"}],[event,{contentVersion:1}],
    [media,{isPremium:true}],[media,{safetyStatus:"error"}],[media,{contentVersion:1}],
    [media,{safetyPolicy:"outdated"}],[media,{archivedAt:new Date()}],
    [owner,{suspended:true}],[owner,{creatorStatus:"rejected"}],[owner,{emailVerifiedAt:null}],
  ]){
    const saved={...target};Object.assign(target,change);
    const denied=await call(path,etag);assert.equal(denied.status,404,JSON.stringify(change));
    assert.equal(denied.headers.get("cache-control"),"private, no-store");assert.equal(denied.headers.get("etag"),null);
    for(const key of Object.keys(target))delete target[key];Object.assign(target,saved);
  }
  const savedMedia=media;media=undefined;assert.equal((await call(path,etag)).status,404);media=savedMedia;
  const savedEvent=event;event=undefined;assert.equal((await call(path,etag)).status,404);event=savedEvent;
}
